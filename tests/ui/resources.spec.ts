import { test, expect } from '@playwright/test'
import { assets, image, saved, tab } from './helpers'

test('clear imported resources, add new content and undo without replacing it', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles([image('IMG_10.svg'), image('IMG_2.svg')])
  await expect(page.locator('.resource-tile')).toHaveCount(2)
  await page.getByRole('button', { name: '保存长图', exact: true }).click()
  await expect(page.locator('[data-composition-id]')).toHaveCount(1)
  await page.getByRole('button', { name: '清空本任务导入素材', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.resource-tile')).toHaveCount(1)
  await page.getByRole('button', { name: '文字卡片', exact: true }).click()
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await saved(page)
  await expect.poll(async () => (await assets(page)).length).toBe(3)
  await tab(page, '资源')
  await expect(page.locator('[data-composition-id]')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.resource-tile')).toHaveCount(4)
})

