test('tasks isolate drafts and resources across switching, refresh, archive and restore', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles(image())
  await expect(page.locator('.resource-tile')).toHaveCount(1)
  await page.getByRole('button', { name: '新建排版任务', exact: true }).click()
  const selector = page.getByRole('combobox', { name: '当前排版任务', exact: true })
  await expect(selector).not.toHaveValue('legacy')
  const second = await selector.inputValue()
  await expect(page.locator('.resource-tile')).toHaveCount(0)
  await page.getByRole('button', { name: '文字卡片', exact: true }).click()
  await saved(page)
  await selector.selectOption('legacy')
  await expect(page.locator('.resource-tile')).toHaveCount(1)
  await expect.poll(async () => (await assets(page))[0]?.type).toBe('photo')
  await selector.selectOption(second)
  await expect(page.locator('.resource-tile')).toHaveCount(1)
  await page.reload()
  await expect(selector).toHaveValue(second)
  await expect.poll(async () => (await assets(page, second))[0]?.type).toBe('text')
  await page.getByRole('button', { name: '管理任务', exact: true }).click()
  await page.getByRole('button', { name: '重命名任务', exact: true }).click()
  await page.getByRole('textbox', { name: '任务名称', exact: true }).fill('第二次旅行')
  await page.locator('.project-rename').getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '归档任务', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '归档任务', exact: true }).click()
  await expect(selector).toHaveValue('legacy')
  await page.getByRole('button', { name: '管理任务', exact: true }).click()
  await page.getByRole('button', { name: '恢复并打开', exact: true }).click()
  await expect(selector).toHaveValue(second)
  await expect(page.locator('.resource-tile')).toHaveCount(1)
})

test('refresh retains the saved composition target and updating keeps its identity', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles(image())
  await saved(page)
  await page.getByRole('button', { name: '保存长图', exact: true }).click()
  const card = page.locator('[data-composition-id]')
  await expect(card).toHaveCount(1)
  const id = await card.getAttribute('data-composition-id')
  await saved(page)
  await page.reload()
  await expect(page.getByRole('button', { name: '更新这张长图', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '文字卡片', exact: true }).click()
  await page.getByRole('button', { name: '更新这张长图', exact: true }).click()
  await expect(card).toHaveCount(1)
  await expect(card).toHaveAttribute('data-composition-id', id!)
  await expect.poll(() => page.evaluate((compositionId) => new Promise<number>((resolve, reject) => {
    const request = indexedDB.open('liubai-collage', 3)
    request.onerror = () => reject(request.error)
    request.onsuccess = () => { const db = request.result; const tx = db.transaction('assets'); const get = tx.objectStore('assets').get(`composition:${compositionId}`); tx.oncomplete = () => { db.close(); resolve(get.result?.blocks.length ?? 0) } }
  }), id)).toBe(2)
})

