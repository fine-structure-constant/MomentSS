import { test, expect } from '@playwright/test'
import { image, saved, tab } from './helpers'
import { readFile } from 'node:fs/promises'

test('white text is legible only in the editor, floating emoji restores selection and artwork survives export', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles(image())
  await page.getByRole('button', { name: '放大并调整：IMG_001.svg', exact: true }).click()
  await page.getByRole('button', { name: '添加图片文字', exact: true }).click()
  const modal = page.getByRole('dialog'), editor = modal.getByRole('textbox', { name: '文字内容', exact: true })
  await editor.fill('白色文字')
  await expect(editor).toHaveClass(/editor-light-text/)
  expect(await editor.evaluate((el) => getComputedStyle(el).textShadow)).not.toBe('none')
  await editor.press('ControlOrMeta+End')
  await modal.getByRole('combobox', { name: 'Emoji 风格', exact: true }).selectOption('twemoji-v17')
  await modal.getByRole('button', { name: 'Emoji', exact: true }).click()
  const picker = modal.locator('.emoji-popover')
  await expect(picker).toBeVisible()
  expect(await picker.evaluate((el) => getComputedStyle(el).position)).toBe('fixed')
  await picker.getByRole('searchbox', { name: '搜索 Emoji', exact: true }).fill('海浪')
  await picker.getByRole('button', { name: /^插入 🌊：/ }).click()
  await expect(editor).toBeFocused()
  await page.keyboard.type('abc')
  await expect(editor).toContainText('白色文字🌊abc')
  await expect(modal.locator('svg image[href*="twemoji-v17"]')).toBeVisible()
  await modal.getByRole('button', { name: 'Emoji', exact: true }).click()
  await picker.getByRole('searchbox').press('Escape')
  await expect(picker).toHaveCount(0)
  await expect(modal).toBeVisible()
  await modal.getByRole('button', { name: '完成', exact: true }).click()
  await saved(page)
  await page.reload()
  await tab(page, '资源')
  await page.locator('.resource-tile__eye').first().click()
  const download = page.waitForEvent('download')
  await page.getByRole('dialog').getByRole('button', { name: /^导出 PNG：/ }).click()
  expect((await readFile((await (await download).path())!)).subarray(1, 4).toString()).toBe('PNG')
})

test('project package restores independently, and a second tab cannot overwrite the owner', async ({ page, context }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles(image())
  await saved(page)
  await page.getByRole('button', { name: '管理任务', exact: true }).click()
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出可编辑项目包', exact: true }).click()
  const path = (await (await event).path())!
  await page.getByRole('button', { name: '新建排版任务', exact: true }).click()
  await expect(page.locator('.resource-tile')).toHaveCount(0)
  if (!await page.getByRole('button', { name: '从项目包恢复为新任务', exact: true }).isVisible()) await page.getByRole('button', { name: '管理任务', exact: true }).click()
  await page.getByLabel('从项目包恢复为新任务', { exact: true }).setInputFiles(path)
  await expect(page.locator('.resource-tile')).toHaveCount(1)
  await expect(page.getByRole('combobox', { name: '当前排版任务', exact: true })).not.toHaveValue('legacy')
  const second = await context.newPage()
  await second.goto('/')
  await expect(second.getByText(/此工作区正在另一个标签页编辑/)).toBeVisible()
  await page.close()
  await second.reload()
  await expect(second.locator('.resource-tile')).toHaveCount(1)
})

test('three-photo weighted row, templates and saved resource grid ZIP remain editable across tool switches', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles([image('one.svg'), image('two.svg'), image('three.svg')])
  await tab(page, '图层')
  await page.getByRole('button', { name: '多选图层', exact: true }).click()
  for (const name of ['one.svg', 'two.svg', 'three.svg']) await page.locator('.layer-multi').getByRole('checkbox', { name, exact: true }).check()
  await page.getByRole('button', { name: '将所选图片组成一行', exact: true }).click()
  await expect(page.locator('.layer-row')).toHaveCount(1)
  await tab(page, '调整')
  const ratios = page.getByRole('textbox', { name: '各图宽度比例（以逗号分隔）', exact: true })
  await ratios.fill('1,2,1'); await ratios.press('Tab')
  await tab(page, '资源')
  await page.getByRole('combobox', { name: '快速插入模板', exact: true }).selectOption('title')
  await saved(page)
  await page.getByRole('button', { name: '保存长图', exact: true }).click()
  await expect(page.locator('[data-composition-id]')).toHaveCount(1)
  await page.locator('.tool-tabs button').nth(2).click()
  await page.getByRole('combobox', { name: '从本任务资源选择', exact: true }).selectOption({ label: '长图 1' })
  await page.getByRole('combobox', { name: '切图格式', exact: true }).selectOption('image/png')
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载切图 ZIP', exact: true }).click()
  expect((await event).suggestedFilename()).toBe('MomentSS-grid.zip')
  await page.locator('.tool-tabs button').first().click()
  await page.locator('.tool-tabs button').nth(2).click()
  await expect(page.getByRole('combobox', { name: '切图格式', exact: true })).toHaveValue('image/png')
  await expect(page.locator('.crop-editor')).toBeVisible()
})

test('cancel keeps completed imports and retry reports only failed files without discarding valid resources', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles(Array.from({ length: 200 }, (_, i) => image(`large-${i}.svg`)))
  await page.getByRole('button', { name: '取消剩余导入', exact: true }).click()
  await expect(page.locator('input[type=file]')).toBeEnabled()
  await expect(page.getByText('已取消，成功导入的资源已保留。', { exact: true })).toBeVisible()
  const kept = await page.locator('.resource-tile').count()
  expect(kept).toBeGreaterThan(0); expect(kept).toBeLessThan(200)
  await page.locator('input[type=file]').setInputFiles([{ name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from('broken') }])
  await expect(page.locator('.import-status li')).toContainText('broken.png')
  await page.getByRole('button', { name: '重试失败文件', exact: true }).click()
  await expect(page.locator('input[type=file]')).toBeEnabled()
  await expect(page.locator('.import-status li')).toContainText('broken.png')
  await expect(page.locator('.resource-tile')).toHaveCount(kept)
})
