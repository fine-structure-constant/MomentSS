import { expect, test } from '@playwright/test'
import { assets, image, saved, tab } from './helpers'

test('an advanced component render error stays inside the editor and retains basic typing', async ({ page }) => {
  await page.route('**/src/components/RichTextEditor.tsx', (route) => route.fulfill({ contentType: 'application/javascript', body: 'export default function BrokenEditor(){throw new Error("simulated-editor-render-error")}' }))
  await page.goto('/')
  await page.getByRole('button', { name: '文字卡片', exact: true }).click(); await tab(page, '调整')
  const input = page.getByRole('textbox', { name: '文字内容', exact: true })
  await input.fill('组件异常也保留')
  await page.getByRole('button', { name: '高级排版', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('内容已保留')
  await expect(input).toHaveValue('组件异常也保留')
  await input.fill('继续输入并保存'); await saved(page)
  expect(JSON.stringify(await assets(page))).toContain('继续输入并保存')
})

test('photo text stays editable when the advanced module fails and preserves the draft across retry', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.route('**/src/components/RichTextEditor.tsx', (route) => route.abort('failed'))
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles(image())
  await page.getByRole('button', { name: '放大并调整：IMG_001.svg', exact: true }).click()
  await page.getByRole('button', { name: '添加图片文字', exact: true }).click()
  const modal = page.getByRole('dialog'), input = modal.getByRole('textbox', { name: '文字内容', exact: true })
  await input.fill('失败时保留文字')
  await modal.getByRole('button', { name: '高级排版', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('内容已保留')
  await expect(input).toHaveValue('失败时保留文字')
  await input.press('End'); await input.pressSequentially('abc')
  await expect(input).toHaveValue('失败时保留文字abc')
  await page.unroute('**/src/components/RichTextEditor.tsx')
  await modal.getByRole('button', { name: '重试高级排版', exact: true }).click()
  await expect(modal.locator('.tiptap')).toHaveText('失败时保留文字abc')
  await modal.getByRole('button', { name: '完成', exact: true }).click()
  await saved(page)
  expect(JSON.stringify(await assets(page))).toContain('失败时保留文字abc')
  expect(errors).toEqual([])
})

test('an unavailable rich editor preserves mixed formatting until the user explicitly converts it', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '文字卡片', exact: true }).click(); await tab(page, '调整')
  await page.getByRole('button', { name: '高级排版', exact: true }).click()
  const editor = page.locator('.tiptap')
  await editor.fill('格式必须保留'); await editor.press('ControlOrMeta+a')
  await page.getByRole('button', { name: '斜体', exact: true }).click()
  await expect(editor.locator('em')).toHaveText('格式必须保留')
  await saved(page)
  const before = JSON.stringify(await assets(page))
  await page.route('**/src/components/RichTextEditor.tsx', (route) => route.abort('failed'))
  await page.reload(); await tab(page, '调整')
  await expect(page.getByRole('alert')).toContainText('局部格式已保留')
  await expect(page.getByRole('textbox', { name: '文字内容', exact: true })).toHaveAttribute('readonly', '')
  expect(JSON.stringify(await assets(page))).toBe(before)
  await page.getByRole('button', { name: '转为基础文字', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click()
  expect(JSON.stringify(await assets(page))).toBe(before)
})

test('a slow extension never delays basic input or steals the current caret', async ({ page }) => {
  await page.route('**/src/components/RichTextEditor.tsx', async (route) => { await new Promise((resolve) => setTimeout(resolve, 2000)); await route.continue() })
  await page.goto('/')
  await page.getByRole('button', { name: '文字卡片', exact: true }).click(); await tab(page, '调整')
  const input = page.getByRole('textbox', { name: '文字内容', exact: true })
  await input.fill('立即输入')
  await page.getByRole('button', { name: '高级排版', exact: true }).click()
  await input.focus(); await input.press('End'); await input.pressSequentially('abc')
  await expect(input).toHaveValue('立即输入abc')
  await expect(page.getByRole('button', { name: '高级排版', exact: true })).toBeEnabled({ timeout: 10000 })
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('立即输入abc')
  await page.getByRole('button', { name: '高级排版', exact: true }).click()
  await expect(page.locator('.tiptap')).toHaveText('立即输入abc')
})

test('HEIC remains opt-in and failed files can be retried without losing normal imports', async ({ page }) => {
  const requests: string[] = []
  page.on('request', (request) => { if (/heic-to/.test(request.url())) requests.push(request.url()) })
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles([image(), { name: 'apple.heic', mimeType: 'image/heic', buffer: Buffer.from('broken') }])
  await expect(page.locator('.resource-tile')).toHaveCount(1)
  await expect(page.locator('.import-status')).toContainText('需要 HEIC 扩展')
  expect(requests).toEqual([])
  await page.getByRole('button', { name: '启用 HEIC 并重试', exact: true }).click()
  await expect(page.locator('.import-status')).toContainText('apple.heic')
  await expect(page.getByRole('button', { name: '重试失败文件', exact: true })).toBeVisible({ timeout: 20000 })
  expect(requests.length).toBeGreaterThan(0)
  await expect(page.locator('.resource-tile')).toHaveCount(1)
  await page.getByRole('button', { name: '扩展', exact: true }).click()
  const plugin = page.locator('.plugin-panel li').filter({ hasText: 'HEIC / HEIF 图片' })
  await plugin.getByRole('button', { name: '停用', exact: true }).click()
  await page.reload()
  await page.locator('input[type=file]').setInputFiles([{ name: 'other.heic', mimeType: 'image/heic', buffer: Buffer.from('broken') }])
  await expect(page.getByRole('button', { name: '启用 HEIC 并重试', exact: true })).toBeVisible()
})
