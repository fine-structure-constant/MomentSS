import { test, expect } from '@playwright/test'
import { image, saved, tab } from './helpers'

test('cover updates preserve identity and export rich text after source resources are cleared', async ({ page }) => {
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles(image())
  await page.getByRole('button', { name: '文字卡片', exact: true }).click()
  await tab(page, '调整')
  await page.getByRole('textbox', { name: '文字内容', exact: true }).fill('旅途 🌊')
  await saved(page)
  await page.getByRole('button', { name: '保存长图', exact: true }).click()
  await expect(page.locator('[data-composition-id]')).toHaveCount(1)
  await page.locator('.tool-tabs button').nth(1).click()
  await page.getByRole('button', { name: '保存封面长图', exact: true }).click()
  const covers = page.locator('[data-composition-id]')
  await expect(covers).toHaveCount(2)
  const coverId = await covers.first().getAttribute('data-composition-id')
  await covers.first().getByRole('button', { name: /调整封面/ }).click()
  await page.getByRole('button', { name: '更新这张封面', exact: true }).click()
  await expect(covers).toHaveCount(2)
  await expect(covers.first()).toHaveAttribute('data-composition-id', coverId!)
  await page.getByRole('button', { name: '清空本任务导入素材', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '删除', exact: true }).click()
  await expect(covers).toHaveCount(2)
  await page.reload()
  await covers.first().locator('.resource-tile__eye').click()
  const download = page.waitForEvent('download')
  await page.getByRole('dialog').getByRole('button', { name: /^导出 PNG：/ }).click()
  expect((await download).suggestedFilename()).toMatch(/\.png$/)
})
