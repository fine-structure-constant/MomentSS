import { test, expect } from '@playwright/test'

test('explicit pack supports a cold page reload, styled emoji editing and PNG export with network disabled', async ({ page, context }) => {
  page.on('pageerror', (error) => console.log('offline page error:', error.message))
  page.on('requestfailed', (request) => console.log('offline request failure:', request.url(), request.failure()?.errorText))
  await page.goto('/')
  await page.getByRole('button', { name: '离线与版本', exact: true }).click()
  await page.getByRole('button', { name: '准备完整离线包', exact: true }).click()
  await expect(page.getByText('完整离线包已就绪，可断网重新打开。', { exact: true })).toBeVisible({ timeout: 90000 })
  await context.setOffline(true)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('combobox', { name: '当前排版任务', exact: true })).toBeVisible({ timeout: 10000 })
  await page.getByRole('button', { name: '文字卡片', exact: true }).click()
  await page.getByRole('tab', { name: '调整', exact: true }).click()
  await page.getByRole('textbox', { name: '文字内容', exact: true }).fill('离线海浪 🌊')
  await page.getByRole('combobox', { name: 'Emoji 风格', exact: true }).selectOption('fluent-v1')
  await expect(page.locator('.structured-preview svg image[href*="fluent-v1"]')).toBeVisible()
  await expect(page.getByText('本地草稿已保存', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '资源', exact: true }).click()
  await page.locator('.resource-tile__eye').first().click()
  const event = page.waitForEvent('download')
  await page.getByRole('dialog').getByRole('button', { name: /^导出 PNG：/ }).click()
  expect((await event).suggestedFilename()).toMatch(/\.png$/)
  await context.setOffline(false)
})
