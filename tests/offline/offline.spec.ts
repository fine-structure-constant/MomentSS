import { test, expect } from '@playwright/test'

test('explicit pack supports a cold page reload, styled emoji editing and PNG export with network disabled', async ({ page, context }) => {
  const heicRequests: string[] = []
  page.on('request', (request) => { if (/\/assets\/heic-to/.test(request.url())) heicRequests.push(request.url()) })
  page.on('pageerror', (error) => console.log('offline page error:', error.message))
  page.on('requestfailed', (request) => console.log('offline request failure:', request.url(), request.failure()?.errorText))
  await page.goto('/')
  await page.getByRole('button', { name: '离线与版本', exact: true }).click()
  await page.getByRole('button', { name: '准备离线资源', exact: true }).click()
  await expect(page.getByText('应用与所选扩展已就绪，可断网重新打开。', { exact: true })).toBeVisible({ timeout: 90000 })
  expect(heicRequests).toEqual([])
  await context.setOffline(true)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('combobox', { name: '当前排版任务', exact: true })).toBeVisible({ timeout: 10000 })
  await page.getByRole('button', { name: '文字卡片', exact: true }).click()
  await page.getByRole('tab', { name: '调整', exact: true }).click()
  await page.getByRole('textbox', { name: '文字内容', exact: true }).fill('离线海浪 🌊')
  await page.getByRole('button', { name: '高级排版', exact: true }).click()
  await expect(page.locator('.tiptap')).toHaveText('离线海浪 🌊')
  await page.getByRole('combobox', { name: 'Emoji 风格', exact: true }).selectOption('fluent-v1')
  await expect(page.locator('.structured-preview svg image[href*="fluent-v1"]')).toBeVisible()
  await expect(page.getByText('本地草稿已保存', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '资源', exact: true }).click()
  await page.locator('.resource-tile__eye').first().click()
  const event = page.waitForEvent('download')
  await page.getByRole('dialog').getByRole('button', { name: /^导出 PNG：/ }).click()
  expect((await event).suggestedFilename()).toMatch(/\.png$/)
  await context.setOffline(false)
})

test('core install skips optional chunks, and HEIC download failure can be retried and removed', async ({ page, context }) => {
  const manifest = await page.request.get('/app-manifest.json').then((response) => response.json())
  const heic = manifest.plugins.heic.files[0]
  expect(manifest.core).not.toContain(heic)
  expect(manifest.core).not.toContain(manifest.plugins['rich-text'].files[0])
  const requested: string[] = []
  page.on('request', (request) => { if ([heic, ...manifest.plugins['rich-text'].files].some((path: string) => request.url().endsWith(path))) requested.push(request.url()) })
  await page.goto('/')
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  expect(requested).toEqual([])
  await page.getByRole('button', { name: '扩展', exact: true }).click()
  const plugin = page.locator('.plugin-panel li').filter({ hasText: 'HEIC / HEIF 图片' })
  await expect(plugin.locator('.plugin-size')).toHaveText('3.0 MB')
  await context.setOffline(true)
  await plugin.getByRole('button', { name: '下载并启用', exact: true }).click()
  await expect(plugin.getByRole('status')).toContainText('下载失败')
  await context.setOffline(false)
  await plugin.getByRole('button', { name: '下载并启用', exact: true }).click()
  await expect(plugin.getByRole('status')).toHaveText('已准备', { timeout: 30000 })
  expect(await page.evaluate(async (url) => !!await (await caches.open('momentss-plugins-v1')).match(url), heic)).toBe(true)
  await plugin.getByRole('button', { name: '移除下载 · HEIC / HEIF 图片', exact: true }).click()
  await expect(plugin.getByRole('status')).toHaveText('停用')
  expect(await page.evaluate(async (url) => !!await (await caches.open('momentss-plugins-v1')).match(url), heic)).toBe(false)
})
