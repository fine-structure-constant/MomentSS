import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
const output = 'design/src/previews/r07-f10'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined, headless: true })
try {
  const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1440, height: 960 } })
  const errors = []; page.on('pageerror', (error) => errors.push(error.message))
  await page.goto(process.argv[2] || 'http://127.0.0.1:4185')
  await page.locator('input[type=file]').setInputFiles(['test-fixtures/coast.svg', 'test-fixtures/street.svg'])
  await page.getByRole('button', { name: '放大并调整：coast.svg', exact: true }).click()
  await page.getByRole('button', { name: '添加图片文字', exact: true }).click()
  const modal = page.getByRole('dialog'), editor = modal.getByRole('textbox', { name: '文字内容', exact: true })
  await editor.fill('白色也要清晰可见 🌊')
  await modal.getByRole('combobox', { name: 'Emoji 风格', exact: true }).selectOption('twemoji-v17')
  await modal.getByRole('button', { name: 'Emoji', exact: true }).click()
  await modal.getByRole('searchbox', { name: '搜索 Emoji', exact: true }).fill('海浪')
  await page.screenshot({ path: `${output}/white-text-floating-desktop.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `${output}/white-text-floating-mobile.png` })
  const popover = await modal.locator('.emoji-popover').boundingBox()
  if (!popover || popover.x < 0 || popover.x + popover.width > 391 || popover.y + popover.height > 845) throw new Error('popover-outside-viewport')
  await modal.getByRole('searchbox').press('Escape')
  await modal.getByRole('button', { name: '完成', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.getByRole('button', { name: '管理任务', exact: true }).click()
  await page.screenshot({ path: `${output}/project-storage-desktop.png` })
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('.tool-tabs button').nth(2).click()
  await page.getByRole('combobox', { name: '从本任务资源选择', exact: true }).selectOption({ label: 'coast.svg' })
  await expect.poll(() => page.locator('.crop-editor canvas').evaluate((canvas) => canvas.getContext('2d').getImageData(30, 30, 1, 1).data[3])).toBeGreaterThan(0)
  await page.screenshot({ path: `${output}/grid-desktop.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('combobox', { name: '界面语言', exact: true }).selectOption('en')
  await expect(page.getByRole('combobox', { name: 'Choose from this task', exact: true })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  await writeFile(`${output}/verification.json`, JSON.stringify({ errors, mobileEnglishOverflow: overflow, popover }, null, 2))
  if (errors.length || overflow) throw new Error('capture-regression')
  console.log(JSON.stringify({ output, errors, overflow }))
} finally { await browser.close() }
